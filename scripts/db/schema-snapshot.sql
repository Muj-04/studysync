-- StudySync schema snapshot generator (READ-ONLY).
--
-- Produces the DDL that recreates StudySync's own database objects:
-- tables, sequences, constraints, indexes, functions, views, triggers, RLS
-- policies and grants in the app schemas, plus the storage buckets, storage /
-- realtime policies, realtime publication membership and cron jobs.
--
-- It only SELECTs from the catalogs and emits no row data (except bucket
-- settings), so it is safe to run against production. Supabase-managed
-- objects (auth, storage and realtime tables, extension functions) are not
-- emitted; they exist on every Supabase project.
--
-- Usage: run in the SQL editor (or psql -At) and save the single text value.
-- scripts/db/build-baseline.cjs turns the output into a migration file.

WITH
app_schemas(nsp) AS (VALUES ('public'), ('recording_private'), ('worker_private'), ('reconcile_archive')),
grantees(rname) AS (VALUES ('anon'), ('authenticated'), ('service_role')),
rels AS (
  SELECT c.oid, n.nspname, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.relreplident
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname IN (SELECT nsp FROM app_schemas)
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'e')
),
tables AS (SELECT * FROM rels WHERE relkind IN ('r', 'p')),
funcs AS (
  SELECT p.oid, n.nspname, p.proname, p.prokind, p.proacl,
         pg_get_function_identity_arguments(p.oid) AS args
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname IN (SELECT nsp FROM app_schemas)
    AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
),
-- ACL helper: one row per (object, grantee, privilege). NULL ACL = defaults.
stmts(ord, sub, txt) AS (
  -- 0 header
  SELECT 0, '', E'SET check_function_bodies = off;\nSET client_min_messages = warning;\n'
  UNION ALL
  -- 1 schemas
  SELECT 1, nsp, format('CREATE SCHEMA IF NOT EXISTS %I;', nsp)
  FROM app_schemas WHERE nsp <> 'public'
  UNION ALL
  -- 2 extensions used by the app
  SELECT 2, e.extname, format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, e.extnamespace::regnamespace::text)
  FROM pg_extension e WHERE e.extname IN ('pgcrypto', 'uuid-ossp', 'pg_net')
  UNION ALL
  SELECT 2, 'pg_cron', 'CREATE EXTENSION IF NOT EXISTS pg_cron;'
  UNION ALL
  -- 3 sequences (not owned by identity columns)
  SELECT 3, r.nspname || '.' || r.relname,
         format('CREATE SEQUENCE IF NOT EXISTS %I.%I AS %s INCREMENT %s MINVALUE %s MAXVALUE %s START %s CACHE %s%s;',
                r.nspname, r.relname, format_type(s.seqtypid, NULL), s.seqincrement, s.seqmin, s.seqmax, s.seqstart, s.seqcache,
                CASE WHEN s.seqcycle THEN ' CYCLE' ELSE '' END)
  FROM rels r JOIN pg_sequence s ON s.seqrelid = r.oid
  WHERE r.relkind = 'S'
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = r.oid AND d.deptype = 'i')
  UNION ALL
  -- 4 tables: columns, types, NOT NULL, identity, generated (defaults later)
  SELECT 4, t.nspname || '.' || t.relname,
         format(E'CREATE TABLE %I.%I (\n%s\n);', t.nspname, t.relname,
           coalesce((
             SELECT string_agg(
               format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                 CASE WHEN a.attcollation <> 0 AND a.attcollation <> (SELECT typcollation FROM pg_type WHERE oid = a.atttypid)
                      THEN ' COLLATE ' || (SELECT format('%I.%I', cn.nspname, co.collname) FROM pg_collation co JOIN pg_namespace cn ON cn.oid = co.collnamespace WHERE co.oid = a.attcollation) ELSE '' END,
                 CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
                 || CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED' ELSE '' END,
                 CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
               E',\n' ORDER BY a.attnum)
             FROM pg_attribute a LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
             WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped), ''))
  FROM tables t
  UNION ALL
  -- 5 functions and procedures
  SELECT 5, f.nspname || '.' || f.proname || '(' || f.args || ')', pg_get_functiondef(f.oid) || ';'
  FROM funcs f
  UNION ALL
  -- 6 column defaults (after functions they may call)
  SELECT 6, t.nspname || '.' || t.relname || '.' || a.attname,
         format('ALTER TABLE %I.%I ALTER COLUMN %I SET DEFAULT %s;', t.nspname, t.relname, a.attname, pg_get_expr(ad.adbin, ad.adrelid))
  FROM tables t JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
  JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
  WHERE a.attgenerated = '' AND a.attidentity = ''
  UNION ALL
  -- 7 sequence ownership
  SELECT 7, r.nspname || '.' || r.relname,
         format('ALTER SEQUENCE %I.%I OWNED BY %I.%I.%I;', r.nspname, r.relname, t.nspname, t.relname, a.attname)
  FROM rels r JOIN pg_depend d ON d.objid = r.oid AND d.deptype = 'a' AND d.refobjsubid > 0
  JOIN tables t ON t.oid = d.refobjid
  JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
  WHERE r.relkind = 'S'
  UNION ALL
  -- 8 primary keys, unique, check, exclusion constraints
  SELECT 8, t.nspname || '.' || t.relname || '.' || lpad(CASE c.contype WHEN 'p' THEN '0' WHEN 'u' THEN '1' ELSE '2' END, 1) || c.conname,
         format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s;', t.nspname, t.relname, c.conname, pg_get_constraintdef(c.oid))
  FROM tables t JOIN pg_constraint c ON c.conrelid = t.oid AND c.contype IN ('p', 'u', 'c', 'x')
  UNION ALL
  -- 9 foreign keys (after every table exists)
  SELECT 9, t.nspname || '.' || t.relname || '.' || c.conname,
         format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s;', t.nspname, t.relname, c.conname, pg_get_constraintdef(c.oid))
  FROM tables t JOIN pg_constraint c ON c.conrelid = t.oid AND c.contype = 'f'
  UNION ALL
  -- 10 indexes not backing a constraint
  SELECT 10, t.nspname || '.' || i.relname, pg_get_indexdef(x.indexrelid) || ';'
  FROM tables t JOIN pg_index x ON x.indrelid = t.oid JOIN pg_class i ON i.oid = x.indexrelid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = x.indexrelid AND c.contype IN ('p', 'u', 'x'))
  UNION ALL
  -- 11 views
  SELECT 11, r.nspname || '.' || r.relname,
         format(E'CREATE OR REPLACE VIEW %I.%I%s AS\n%s', r.nspname, r.relname,
           CASE WHEN c.reloptions IS NOT NULL THEN ' WITH (' || array_to_string(c.reloptions, ', ') || ')' ELSE '' END,
           pg_get_viewdef(r.oid, true))
  FROM rels r JOIN pg_class c ON c.oid = r.oid WHERE r.relkind = 'v'
  UNION ALL
  -- 12 triggers on app tables, and app-owned triggers on auth/storage tables
  SELECT 12, tg.tgrelid::regclass::text || '.' || tg.tgname, pg_get_triggerdef(tg.oid, true) || ';'
  FROM pg_trigger tg JOIN pg_proc p ON p.oid = tg.tgfoid JOIN pg_namespace pn ON pn.oid = p.pronamespace
  WHERE NOT tg.tgisinternal AND pn.nspname IN (SELECT nsp FROM app_schemas)
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = tg.oid AND d.deptype = 'e')
  UNION ALL
  -- 13 row level security switches and replica identity
  SELECT 13, t.nspname || '.' || t.relname,
         concat_ws(E'\n',
           CASE WHEN t.relrowsecurity THEN format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY;', t.nspname, t.relname) END,
           CASE WHEN t.relforcerowsecurity THEN format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY;', t.nspname, t.relname) END,
           CASE t.relreplident WHEN 'f' THEN format('ALTER TABLE %I.%I REPLICA IDENTITY FULL;', t.nspname, t.relname) END)
  FROM tables t WHERE t.relrowsecurity OR t.relforcerowsecurity OR t.relreplident = 'f'
  UNION ALL
  -- 14 policies on app tables, storage.objects, storage.buckets and realtime.messages
  SELECT 14, pc.relnamespace::regnamespace::text || '.' || pc.relname || '.' || pol.polname,
         concat_ws(E'\n',
           CASE WHEN pc.relnamespace::regnamespace::text IN ('storage', 'realtime')
                THEN format('DROP POLICY IF EXISTS %I ON %I.%I;', pol.polname, pc.relnamespace::regnamespace::text, pc.relname) END,
           format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
             pol.polname, pc.relnamespace::regnamespace::text, pc.relname,
             CASE WHEN pol.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
             CASE pol.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
             CASE WHEN pol.polroles = '{0}' THEN 'public'
                  ELSE (SELECT string_agg(quote_ident(rolname), ', ' ORDER BY rolname) FROM pg_roles WHERE oid = ANY(pol.polroles)) END,
             CASE WHEN pol.polqual IS NOT NULL THEN E'\n  USING (' || pg_get_expr(pol.polqual, pol.polrelid) || ')' ELSE '' END,
             CASE WHEN pol.polwithcheck IS NOT NULL THEN E'\n  WITH CHECK (' || pg_get_expr(pol.polwithcheck, pol.polrelid) || ')' ELSE '' END))
  FROM pg_policy pol JOIN pg_class pc ON pc.oid = pol.polrelid
  WHERE pc.relnamespace::regnamespace::text IN (SELECT nsp FROM app_schemas)
     OR (pc.relnamespace::regnamespace::text = 'storage' AND pc.relname IN ('objects', 'buckets'))
     OR (pc.relnamespace::regnamespace::text = 'realtime' AND pc.relname = 'messages')
  UNION ALL
  -- 15 schema privileges
  SELECT 15, nsp,
         concat_ws(E'\n',
           format('REVOKE ALL ON SCHEMA %I FROM PUBLIC, anon, authenticated, service_role;', nsp),
           (SELECT string_agg(format('GRANT %s ON SCHEMA %I TO %s;', a.privilege_type, nsp,
                     CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(g.rolname) END), E'\n' ORDER BY g.rolname, a.privilege_type)
            FROM pg_namespace n, aclexplode(n.nspacl) a LEFT JOIN pg_roles g ON g.oid = a.grantee
            WHERE n.nspname = nsp AND (a.grantee = 0 OR g.rolname IN (SELECT rname FROM grantees))))
  FROM app_schemas WHERE nsp <> 'public'
  UNION ALL
  -- 16 table and sequence privileges (whole-object)
  SELECT 16, r.nspname || '.' || r.relname,
         concat_ws(E'\n',
           format('REVOKE ALL ON %s %I.%I FROM PUBLIC, anon, authenticated, service_role;',
                  CASE r.relkind WHEN 'S' THEN 'SEQUENCE' ELSE 'TABLE' END, r.nspname, r.relname),
           (SELECT string_agg(format('GRANT %s ON %s %I.%I TO %s;', a.privilege_type,
                     CASE r.relkind WHEN 'S' THEN 'SEQUENCE' ELSE 'TABLE' END, r.nspname, r.relname,
                     CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(g.rolname) END), E'\n' ORDER BY g.rolname, a.privilege_type)
            FROM pg_class c, aclexplode(c.relacl) a LEFT JOIN pg_roles g ON g.oid = a.grantee
            WHERE c.oid = r.oid AND (a.grantee = 0 OR g.rolname IN (SELECT rname FROM grantees))))
  FROM rels r WHERE r.relkind IN ('r', 'p', 'v', 'S')
  UNION ALL
  -- 17 column privileges
  SELECT 17, t.nspname || '.' || t.relname || '.' || at.attname,
         string_agg(format('GRANT %s (%I) ON TABLE %I.%I TO %s;', a.privilege_type, at.attname, t.nspname, t.relname,
                    CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(g.rolname) END), E'\n' ORDER BY g.rolname, a.privilege_type)
  FROM tables t JOIN pg_attribute at ON at.attrelid = t.oid AND at.attnum > 0 AND NOT at.attisdropped AND at.attacl IS NOT NULL,
       aclexplode(at.attacl) a LEFT JOIN pg_roles g ON g.oid = a.grantee
  WHERE a.grantee = 0 OR g.rolname IN (SELECT rname FROM grantees)
  GROUP BY t.nspname, t.relname, at.attname
  UNION ALL
  -- 18 function privileges (NULL ACL = PostgreSQL default: EXECUTE to PUBLIC)
  SELECT 18, f.nspname || '.' || f.proname || '(' || f.args || ')',
         concat_ws(E'\n',
           format('REVOKE ALL ON %s %I.%I(%s) FROM PUBLIC, anon, authenticated, service_role;',
                  CASE f.prokind WHEN 'p' THEN 'PROCEDURE' ELSE 'FUNCTION' END, f.nspname, f.proname, f.args),
           CASE WHEN f.proacl IS NULL
                THEN format('GRANT EXECUTE ON FUNCTION %I.%I(%s) TO PUBLIC;', f.nspname, f.proname, f.args)
                ELSE (SELECT string_agg(format('GRANT EXECUTE ON %s %I.%I(%s) TO %s;',
                         CASE f.prokind WHEN 'p' THEN 'PROCEDURE' ELSE 'FUNCTION' END, f.nspname, f.proname, f.args,
                         CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(g.rolname) END), E'\n' ORDER BY g.rolname)
                      FROM aclexplode(f.proacl) a LEFT JOIN pg_roles g ON g.oid = a.grantee
                      WHERE a.privilege_type = 'EXECUTE' AND (a.grantee = 0 OR g.rolname IN (SELECT rname FROM grantees))) END)
  FROM funcs f
  UNION ALL
  -- 19 realtime publication membership
  SELECT 19, pt.schemaname || '.' || pt.tablename,
         format(E'DO $pub$ BEGIN\n  IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = ''supabase_realtime'' AND schemaname = %L AND tablename = %L) THEN\n    ALTER PUBLICATION supabase_realtime ADD TABLE %I.%I;\n  END IF;\nEND $pub$;',
                pt.schemaname, pt.tablename, pt.schemaname, pt.tablename)
  FROM pg_publication_tables pt WHERE pt.pubname = 'supabase_realtime'
  UNION ALL
  -- 20 storage buckets (settings only, no objects)
  SELECT 20, b.id,
         format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %s, %s, %s) ON CONFLICT (id) DO UPDATE SET public = EXCLUDED.public, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;',
                b.id, b.name, CASE WHEN b.public THEN 'true' ELSE 'false' END, coalesce(b.file_size_limit::text, 'NULL'),
                coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'NULL'))
  FROM storage.buckets b
  UNION ALL
  -- 21 cron jobs (the recording worker needs the project URL: scheduled by a function call)
  SELECT 21, j.jobname,
         CASE WHEN j.command ILIKE '%recording-worker%'
              THEN format(E'-- %s: run once per project after deploying the edge function:\n-- SELECT public.schedule_recording_worker(''https://<project-ref>.supabase.co'');', j.jobname)
              ELSE format('SELECT cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command) END
  FROM cron.job j
)
SELECT string_agg(txt, E'\n\n' ORDER BY ord, sub) AS ddl
FROM stmts WHERE txt IS NOT NULL AND txt <> '';
